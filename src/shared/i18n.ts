export const LANGUAGES = ['auto', 'ru', 'en'] as const
export type LanguageSetting = (typeof LANGUAGES)[number]
export type Lang = 'ru' | 'en'

/** Resolves 'auto' against a BCP-47 locale such as "ru-RU" or "en-US" */
export function resolveLang(setting: LanguageSetting, locale: string): Lang {
  if (setting === 'ru' || setting === 'en') return setting
  return locale.toLowerCase().startsWith('ru') ? 'ru' : 'en'
}

